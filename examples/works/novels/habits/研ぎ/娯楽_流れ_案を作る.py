def drafts():
    out = {}
    for p in sorted(glob.glob(os.path.join(EX, "habits-0*", "草稿", "draft_*.md"))):
        name = os.path.basename(p)
        out[name[len("draft_"):len("draft_") + 5]] = p
    return out


def main():
    write = "--write" in sys.argv
    d = drafts()
    rows, pending, bad = [], [], 0
    for vol, ep, num, old, new, view, why in ROWS:
        p = d.get(ep)
        if p is None:
            print(f"⛔ 草稿が無い: {ep}")
            bad += 1
            continue
        body = open(p, encoding="utf-8").read().split("\n")
        if num > len(body):
            print(f"⛔ 行が無い: {ep}:{num}（全 {len(body)} 行）")
            bad += 1
            continue
        now = body[num - 1]
        rel = os.path.relpath(p, EX)
        if now == new:
            state = "✅ 当て済み"
        elif now == old:
            state = "　 未当て"
            pending.append((vol, ep, num, old, new, rel))
        else:
            print(f"⛔ 草稿の行が、旧にも新にも一致しない: {ep}:{num}")
            print(f"  草稿: {now}")
            print(f"  旧  : {old}")
            bad += 1
            continue
        rows.append((vol, ep.split("-")[1], num, old, new, view, why, rel))
        print(f"{state} {ep}:{num}")
    if bad:
        print(f"\n⛔ {bad} 件。書かない。")
        return 1
    n_done = len(rows) - len(pending)
    print(f"\n✅ 計 {len(rows)} 件（当て済み {n_done} 件・未当て {len(pending)} 件）。")
    if write:
        dest = os.path.join(ROOT, "娯楽_流れ_案.tsv")
        with open(dest, "w", encoding="utf-8") as f:
            f.write(HEADER)
            for row in rows:
                f.write("\t".join(str(x) for x in row[:7]) + "\n")
        print(f"書いた: {dest}")

        swap = os.path.join(ROOT, "娯楽_流れ_差し替え.tsv")
        with open(swap, "w", encoding="utf-8") as f:
            f.write("# 娯楽_流れ_案.tsv（7欄）のうち、**まだ当てていない行**から作った、"
                    "差し替える.py 用の4欄台帳。パスは examples/ からの相対ゆえ、`cd examples` から当てる。\n")
            for vol, ep, num, old, new, rel in pending:
                f.write("\t".join([rel, str(num), old, new]) + "\n")
        print(f"書いた: {swap}（未当て {len(pending)} 件）")
    return 0


if __name__ == "__main__":
    sys.exit(main())

