"""娯楽_型_案_02.tsv を作る。

**④ 場面の型**——**場面1の第一行（入口）に、設計「入口の掴み」が名指しした
〈Y〉（掴みの一文）を置く。**

場面表の「入口の掴み」の欄は、`**第一場面の第一文——〈X〉。** 〈Y〉` の形をしている。
実測（2026-10-14、私が 63 枚を照合した）＝**〈Y〉が第一行に無い話が 33＋27＝60、
〈X〉と〈Y〉の両方が第一行に在る話は 3（`01-08`・`02-04`・`02-05`）。**

ゆえに手は一つ——**第一行の内側で、いちばん平らな一文を、〈Y〉へ入れ替える。**
行は足さない。段落も足さない。**文数は増やさない**（`台帳を検める.py` の制約）。
**新しい物も、新しい動作も足さない。〈Y〉は設計が既に名指しした字である。**

    python3 娯楽_型_案を作る.py            # 画面へ出す
    python3 娯楽_型_案を作る.py --write    # 娯楽_型_案_02.tsv へ書く
"""
