SETUP = {("02", "02-01", 15)}       # 既に回収を持つ場面——仕込みを立てる側で打つ


def drafts():
    """{話番号: パス} を、草稿から作る。"""
    out = {}
    for p in sorted(glob.glob(os.path.join(EX, "habits-0*", "草稿", "draft_*.md"))):
        name = os.path.basename(p)
        out[name[len("draft_"):len("draft_") + 5]] = p      # 01-01
    return out


def main():
    write = "--write" in sys.argv
    d = drafts()
    lines = []
    bad = 0
    for vol, ep, num, new, path, why in ROWS:
        p = d.get(ep)
        if p is None:
            print(f"⛔ 草稿が無い: {ep}")
            bad += 1
            continue
        with open(p, encoding="utf-8") as f:
            body = f.read().split("\n")
        if num > len(body):
            print(f"⛔ 行が無い: {ep}:{num}（全 {len(body)} 行）")
            bad += 1
            continue
        old = body[num - 1]
        if not old.strip():
            print(f"⛔ 空行である: {ep}:{num}")
            bad += 1
            continue
        te = "仕込みを立てる" if (vol, ep, num) in SETUP else "回収を打つ"
        # ⚠ `台帳を検める.py` は `f"{parts[0]}-{parts[1]}"` で話を引く。
        #   ゆえに第一欄＝巻、第二欄＝話番号（二桁）であって、`01-01` ではない。
        rel = os.path.relpath(p, EX)                     # habits-01/草稿/draft_….md
        lines.append((vol, ep.split("-")[1], num, old, new, f"{te}（通路＝{path}）", why, rel))
        print(f"--- {ep}:{num}")
        print(f"  いま: {old}")
        print(f"  案  : {new}")
    if bad:
        print(f"\n⛔ {bad} 件。書かない。")
        return 1
    print(f"\n✅ {len(lines)} 件。")
    if write:
        dest = os.path.join(ROOT, "娯楽_声_案.tsv")
        with open(dest, "w", encoding="utf-8") as f:
            f.write(HEADER)
            for row in lines:
                f.write("\t".join(str(x) for x in row[:7]) + "\n")
        print(f"書いた: {dest}")

        swap = os.path.join(ROOT, "娯楽_声_差し替え.tsv")
        with open(swap, "w", encoding="utf-8") as f:
            f.write("# 娯楽_声_案.tsv（7欄）から作った、差し替える.py 用の4欄台帳。"
                    "パスは examples/ からの相対ゆえ、`cd examples` から当てる。\n")
            for row in lines:
                f.write("\t".join([row[7], str(row[2]), row[3], row[4]]) + "\n")
        print(f"書いた: {swap}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
